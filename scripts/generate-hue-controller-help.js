#!/usr/bin/env node
'use strict'

const fs = require('fs')
const path = require('path')
const { profiles, locales } = require('./hue-controller-profiles/catalog')
const content = require('./hue-controller-help/content.json')

const projectRoot = path.resolve(__dirname, '..')
const controllerPath = path.join(projectRoot, 'nodes', 'hueUltimateController.html')
const checkMode = process.argv.includes('--check')
const tutorialUrl = 'https://www.youtube.com/playlist?list=PL9Yh1bjbLAYrU8PsVhW4xzEug2WtVFv3E'
const migrationVideoUrl = 'https://youtu.be/f0Evf2QFI7c'
const helpPattern = /<script type="text\/markdown" data-help-name="hueUltimateController">[\s\S]*?<\/script>\s*$/

const labelsForLocale = (locale) => {
  const localePath = path.join(projectRoot, 'nodes', 'locales', locale, 'hueUltimateController.json')
  const messages = JSON.parse(fs.readFileSync(localePath, 'utf8'))
  return messages.hueUltimateController.types
}

const targetMarkup = (value, target) => {
  if (target !== 'wiki') return value
  return String(value).replace(/<code>([^<]+)<\/code>/g, '`$1`')
}

const renderBody = (locale, target) => {
  const localized = content[locale]
  const labels = labelsForLocale(locale)
  if (!localized) throw new Error(`Missing HUE Controller help content for locale: ${locale}`)

  const missingProfiles = Object.keys(profiles).filter((controllerType) => (
    !localized.profiles[controllerType] || !labels[controllerType]
  ))
  if (missingProfiles.length) {
    throw new Error(`Missing ${locale} HUE Controller profile help: ${missingProfiles.join(', ')}`)
  }

  const anchorPrefix = target === 'wiki' ? 'hue-controller-docs' : 'hue-controller-help'
  const lines = [
    '<!-- GENERATED by scripts/generate-hue-controller-help.js. -->',
    ''
  ]
  if (target === 'help') lines.push('## HUE Controller', '')
  lines.push(
    targetMarkup(localized.intro, target),
    '',
    `[${localized.tutorials}](${tutorialUrl})`,
    '',
    `## ${localized.quickStartTitle}`,
    ''
  )

  localized.quickStart.forEach((step, index) => lines.push(`${index + 1}. ${targetMarkup(step, target)}`))

  lines.push(
    '',
    `## ${localized.messagesTitle}`,
    '',
    targetMarkup(localized.messagesIntro, target),
    '',
    '```js',
    "msg.topic = 'living-room/brightness'",
    'msg.payload = 60',
    'return msg',
    '```',
    '',
    targetMarkup(localized.payloads, target),
    '',
    `### ${localized.nativeInputTitle}`,
    '',
    targetMarkup(localized.nativeInput, target),
    '',
    '```js',
    'msg = { on: { on: true } }',
    'return msg',
    '```',
    '',
    targetMarkup(localized.nativeInputNote, target),
    '',
    `## ${localized.optionalTitle}`,
    '',
    targetMarkup(localized.optional, target),
    '',
    `## ${localized.editorTitle}`,
    ''
  )

  localized.editor.forEach((item) => lines.push(`- ${targetMarkup(item, target)}`))

  lines.push(
    '',
    `## ${localized.migrationTitle}`,
    '',
    targetMarkup(localized.migration, target),
    '',
    `[${localized.migrationVideo}](${migrationVideoUrl})`,
    '',
    target === 'wiki'
      ? '<!-- HUE_CONTROLLER_PROFILE_DOCS_START -->'
      : '<!-- HUE_CONTROLLER_PROFILE_HELP_START -->',
    '',
    `## ${localized.profilesTitle}`,
    '',
    targetMarkup(localized.profilesIntro, target),
    ''
  )

  Object.keys(profiles).forEach((controllerType) => {
    lines.push(`- [${labels[controllerType]} (\`${controllerType}\`)](#${anchorPrefix}-${controllerType})`)
  })

  Object.keys(profiles).forEach((controllerType) => {
    lines.push(
      '',
      `<span id="${anchorPrefix}-${controllerType}" data-hue-controller-type="${controllerType}"></span>`,
      '',
      `### ${labels[controllerType]} (\`${controllerType}\`)`,
      '',
      targetMarkup(localized.profiles[controllerType], target)
    )
  })

  lines.push(
    '',
    target === 'wiki'
      ? '<!-- HUE_CONTROLLER_PROFILE_DOCS_END -->'
      : '<!-- HUE_CONTROLLER_PROFILE_HELP_END -->'
  )

  return lines.join('\n').trim()
}

const renderHelp = (locale) => (
  `<script type="text/markdown" data-help-name="hueUltimateController">\n${renderBody(locale, 'help')}\n</script>\n`
)

const renderWiki = (locale) => {
  const permalinkPrefix = locale === 'en' ? '' : `${locale}-`
  const localized = content[locale]
  return `---
layout: wiki
title: "HUE Controller"
lang: ${locale}
permalink: /wiki/${permalinkPrefix}HUE%20Controller
---
# HUE Controller

<div data-hue-controller-overview="hero" style="margin:18px 0 28px;padding:22px;border-radius:14px;background:#1767bf;color:#fff;">
  <strong style="font-size:1.35rem;">${localized.tagline}</strong>
</div>

${renderBody(locale, 'wiki')}
`
}

const expectedFiles = new Map()
locales.forEach((locale) => {
  expectedFiles.set(
    path.join(projectRoot, 'nodes', 'locales', locale, 'hueUltimateController.html'),
    renderHelp(locale)
  )
  const wikiName = locale === 'en' ? 'HUE Controller.md' : `${locale}-HUE Controller.md`
  expectedFiles.set(path.join(projectRoot, 'docs', 'wiki', wikiName), renderWiki(locale))
})

const controllerSource = fs.readFileSync(controllerPath, 'utf8')
if (!helpPattern.test(controllerSource)) {
  throw new Error('Unable to find the HUE Controller help block in nodes/hueUltimateController.html')
}
expectedFiles.set(
  controllerPath,
  `${controllerSource.replace(helpPattern, '').trimEnd()}\n\n${renderHelp('en')}`
)

const staleFiles = []
expectedFiles.forEach((expected, filePath) => {
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : ''
  if (current === expected) return
  if (checkMode) {
    staleFiles.push(path.relative(projectRoot, filePath))
  } else {
    fs.writeFileSync(filePath, expected)
  }
})

if (checkMode && staleFiles.length) {
  console.error(`HUE Controller help is stale: ${staleFiles.join(', ')}`)
  console.error('Run: npm run hue-controller-help:generate')
  process.exit(1)
}

if (checkMode) {
  console.log('HUE Controller help and wiki documentation are current')
} else {
  console.log('Generated localized HUE Controller help and wiki documentation')
}
